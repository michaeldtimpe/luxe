"""LUXE_ABORT_REPORT: a write run whose model text is empty gets a
Python-built report (luxe/abortreport.py, maintain._abort_report).

End-to-end through `maintain_pipeline` with the harness from
test_maintain_pipeline (model, gh and oMLX stubbed; git real)."""

from __future__ import annotations

import re

import pytest

from luxe import abortreport, steplimit
from luxe.tools.base import ToolCall
from tests.test_maintain_pipeline import Harness, Pass

_STUCK = "Stuck in loop — repeated same tool calls 2 consecutive turns"
_NEW = "def add(a, b):\n    return a + b\n\n\ndef mul(a, b):\n    return a * b\n"
# Wording a fallback report must never contain: it states facts, not verdicts.
_CLAIMS = re.compile(r"\b(correct(ly)?|works|fixed|succe(ss|eded)|complete[ds]?|"
                     r"all tests pass|verified)\b", re.I)


@pytest.fixture
def h(tmp_path, monkeypatch) -> Harness:
    return Harness(tmp_path, monkeypatch)


def _tc(name: str, args: dict, result: str = "", error: str | None = None,
        **kw) -> ToolCall:
    return ToolCall(id=name, name=name, arguments=args, result=result,
                    error=error, **kw)


def _calls() -> list[ToolCall]:
    return [
        _tc("read_file", {"path": "src/calc.py"}, "def add..."),
        _tc("bash", {"command": "pytest -q"}, "1 failed", "exit code 1"),
        _tc("edit_file", {"path": "src/calc.py"}, "ok"),
        _tc("bash", {"command": "pytest -q"}, "....\n2 passed in 0.01s\n"),
        _tc("bash", {"command": "pytest -q 2>&1 | tail -3"}, "",
            "Shell operators not allowed: '|'"),
        _tc("lint", {"path": "src/calc.py"}, "src/calc.py:1: E1", "exit code 1"),
        _tc("read_file", {"path": "README.md"}, "# calc"),
        _tc("bash", {"command": "pytest -q"}, "", None, duplicate=True),
    ]


def test_stuck_loop_with_a_diff_gets_a_fallback_report(h):
    h.script = [Pass(text="", aborted=True, reason=_STUCK,
                     writes={"src/calc.py": _NEW}, tool_calls=_calls())]
    t = h.run()
    rep = t.synthesizer
    assert rep is not None
    assert rep.startswith("> **Report generated by luxe, not written by the model.**")
    assert "stuck-loop abort" in rep and _STUCK in rep
    assert "- `src/calc.py` (+4/-0)" in rep
    # Only calls after the LAST write, verification tools only, in order.
    cmds = rep.split("## Commands run after the last file write")[1]
    assert cmds.strip().splitlines() == [
        '- `pytest -q`: exit 0; last output line: "2 passed in 0.01s"',
        "- `pytest -q 2>&1 | tail -3`: refused, not run: "
        "Shell operators not allowed: '|'",
        '- `lint src/calc.py`: exit 1; last output line: "src/calc.py:1: E1"',
        "- `pytest -q`: not re-run (repeat of an earlier call)",
    ]
    assert "1 failed" not in rep          # before the last write
    assert not _CLAIMS.search(rep.replace("make no claim that the change is "
                                          "correct", ""))
    # Same text reaches the commit/PR body; the PR is not drafted for it.
    [pr] = t.pr_calls
    assert pr["report_text"] == rep and pr["incomplete"] is False
    assert t.event("abort_report_written") == {
        "kind": "abort_report_written", "reason": "stuck-loop abort",
        "abort_reason": _STUCK, "files": ["src/calc.py"], "n_commands": 4}
    # The model's text is still measured as empty.
    assert t.event("single_mode_done")["final_text_chars"] == 0
    assert t.kinds().index("cleanup_turn") < t.kinds().index("abort_report_written")


def test_normal_finish_is_unchanged(h):
    h.script = [Pass(writes={"src/calc.py": _NEW}, tool_calls=_calls())]
    t = h.run()
    assert "abort_report_written" not in t.kinds()
    assert t.synthesizer == "Done." and t.pr_calls[0]["report_text"] == "Done."


def test_flag_zero_is_byte_identical_to_no_report(h, monkeypatch):
    monkeypatch.setenv("LUXE_ABORT_REPORT", "0")
    h.script = [Pass(text="", aborted=True, reason=_STUCK,
                     writes={"src/calc.py": _NEW}, tool_calls=_calls())]
    t = h.run()
    assert "abort_report_written" not in t.kinds()
    assert t.synthesizer is None and t.pr_calls[0]["report_text"] == ""


@pytest.mark.parametrize("value,on", [(None, True), ("0", False), ("1", True),
                                      ("", True), ("false", True)])
def test_flag_grammar(monkeypatch, value, on):
    if value is None:
        monkeypatch.delenv("LUXE_ABORT_REPORT", raising=False)
    else:
        monkeypatch.setenv("LUXE_ABORT_REPORT", value)
    assert abortreport.enabled() is on


def test_no_diff_says_the_run_made_no_change(h):
    h.script = [Pass(text="", aborted=True, reason="Backend error: boom")]
    t = h.run()
    rep = t.synthesizer
    assert "backend error: Backend error: boom" in rep
    assert "- none: the run made no change to the repository" in rep
    assert rep.rstrip().endswith("- none recorded")
    assert t.event("abort_report_written")["files"] == []


def test_read_only_task_never_gets_one(h):
    h.script = [Pass(text="")]
    t = h.run(task="review", goal="Review calc")
    assert "abort_report_written" not in t.kinds() and t.synthesizer is None


def test_idle_exit_reason_comes_from_the_event_log(h, monkeypatch):
    from luxe import run_state

    def fake_single(*a, **kw):
        run_state.append_event(kw["run_id"], "post_write_idle_exit", step=9)
        (h.repo / "src" / "calc.py").write_text(_NEW)
        from luxe.agents.loop import AgentResult
        return AgentResult(final_text="", steps=9, tool_calls=_calls())
    from luxe.agents import single
    monkeypatch.setattr(single, "run_single", fake_single)
    t = h.run()
    assert t.event("abort_report_written")["reason"] == "post-write idle exit"
    assert "(post-write idle exit)" in t.synthesizer


def test_step_limited_run_keeps_its_incomplete_note_on_top(h):
    h.script = [Pass(text="", aborted=True, reason="Max steps reached (30)",
                     writes={"src/calc.py": _NEW}, tool_calls=_calls())]
    t = h.run()
    assert t.synthesizer.startswith(steplimit.REPORT_NOTE + "\n\n> **Report "
                                    "generated by luxe")
    assert t.pr_calls[0]["incomplete"] is True
    assert t.event("abort_report_written")["reason"] == "step limit"


def test_whitespace_only_model_text_counts_as_empty(h):
    h.script = [Pass(text="  \n", aborted=True, reason=_STUCK,
                     writes={"src/calc.py": _NEW})]
    t = h.run()
    assert "abort_report_written" in t.kinds()


def test_files_changed_counts_hunk_lines_only():
    diff = ("diff --git a/x.py b/x.py\n--- a/x.py\n+++ b/x.py\n@@ -1,2 +1,2 @@\n"
            "--- not a header\n+++ also content\n ctx\n"
            "diff --git a/new.txt b/new.txt\nnew file mode 100644\n"
            "--- /dev/null\n+++ b/new.txt\n@@ -0,0 +1 @@\n+hi\n")
    assert abortreport.files_changed(diff) == [("x.py", 1, 1), ("new.txt", 1, 0)]


def test_no_successful_write_lists_no_commands():
    calls = [_tc("edit_file", {"path": "a"}, "", "old_string not found"),
             _tc("bash", {"command": "pytest -q"}, "ok")]
    assert abortreport.commands_after_last_write(calls) == []


def test_timeout_and_tool_error_outcomes():
    calls = [_tc("write_file", {"path": "a"}, "ok"),
             _tc("bash", {"command": "pytest"}, "", "Command timed out after 120s"),
             _tc("typecheck", {"path": "a"}, "", "ValueError: nope")]
    assert abortreport.commands_after_last_write(calls) == [
        ("pytest", "timed out"), ("typecheck a", "tool error: ValueError: nope")]


