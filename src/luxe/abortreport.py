"""Abort report: a model-free report for a write run that ended with no text.

Found 2026-11-19 (acceptance/idle_capped_ab_2026_11/REPORT.md): when the agent
loop ends early (the stuck-loop guard, post_write_idle_exit, a backend error)
its final text is empty, so `luxe maintain` wrote no report: synthesizer.md,
the commit body and the PR body carried nothing. On
the-game-implement-shuffle-shortcut every arm wrote a correct patch and then
produced no report. A model "final turn" asking for one was REFUTED (the model
answered with a tool call 9/9) and removed; this module makes NO model call.

LUXE_ABORT_REPORT (default ON; only the exact string "0" disables): when a
write task's model text is empty, `maintain` builds the report here from facts
the run recorded: why it ended, the files changed vs the base commit, and the
verification commands run after the last write with their exit status. It
states nothing about correctness. `AgentResult.final_text` is never touched,
so `single_mode_done.final_text_chars` still measures the MODEL's text; the
`abort_report_written` event tells a fallback report from a model report.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path
from typing import Any, Iterable

#: First line of every fallback report; analysis can match on it.
REPORT_HEADER = (
    "> **Report generated by luxe, not written by the model.** The run ended "
    "before the model wrote a report ({reason}). The facts below come from the "
    "run's records: the files changed against the base commit and the "
    "commands run after the last file write. They make no claim that the "
    "change is correct. Review the diff before merging."
)

WRITE_TOOLS = frozenset({"write_file", "edit_file"})
#: Tools counted as verification (bash + the analyzer tools).
VERIFY_TOOLS = frozenset({"bash", "lint", "typecheck", "lint_js",
                          "typecheck_ts", "lint_rust", "vet_go"})
MAX_COMMANDS = 12
MAX_FILES = 40
_CMD_CHARS = 120
_LINE_CHARS = 120
_EXIT_RE = re.compile(r"^exit code (-?\d+)")


def enabled() -> bool:
    """Default ON; only the exact string "0" disables."""
    return os.environ.get("LUXE_ABORT_REPORT", "1") != "0"


def event_kinds(events_path: Path) -> set[str]:
    """Kinds recorded in a run's events.jsonl; empty when unreadable."""
    kinds: set[str] = set()
    try:
        lines = events_path.read_text(errors="replace").splitlines()
    except OSError:
        return kinds
    for ln in lines:
        try:
            kinds.add(json.loads(ln).get("kind", ""))
        except (json.JSONDecodeError, AttributeError):
            continue
    return kinds


def end_reason(result: Any, kinds: Iterable[str] = ()) -> tuple[str, str]:
    """(short category, raw detail) for why the run ended without text."""
    raw = (getattr(result, "abort_reason", "") or "").strip()
    low = raw.lower()
    if "stuck" in low or "repeated same tool calls" in low:
        return "stuck-loop abort", raw
    if "max steps" in low:
        return "step limit", raw
    if low.startswith("backend error") or "backend error" in low:
        return "backend error", raw
    if raw:
        return "aborted", raw
    if "post_write_idle_exit" in set(kinds):
        return "post-write idle exit", ""
    return "final turn carried no text", ""


def files_changed(diff_text: str) -> list[tuple[str, int, int]]:
    """(path, additions, deletions) per file in a `git diff` text, in order."""
    out: list[list] = []
    in_hunk = False
    for line in (diff_text or "").splitlines():
        if line.startswith("diff --git "):
            m = re.match(r"diff --git a/(.*) b/(.*)$", line)
            out.append([m.group(2) if m else line[11:], 0, 0])
            in_hunk = False
        elif line.startswith("@@"):
            in_hunk = True
        elif not out or not in_hunk:
            continue
        elif line.startswith("+"):
            out[-1][1] += 1
        elif line.startswith("-"):
            out[-1][2] += 1
    return [(p, a, d) for p, a, d in out]


def _last_line(text: str) -> str:
    for line in reversed((text or "").splitlines()):
        if line.strip():
            s = line.strip()
            return s if len(s) <= _LINE_CHARS else s[:_LINE_CHARS] + "…"
    return ""


def _label(tc: Any) -> str:
    args = getattr(tc, "arguments", None) or {}
    if tc.name == "bash":
        cmd = str(args.get("command", "")).strip()
    else:
        target = args.get("path") or args.get("file") or ""
        cmd = f"{tc.name} {target}".strip()
    cmd = " ".join(cmd.split())
    return cmd if len(cmd) <= _CMD_CHARS else cmd[:_CMD_CHARS] + "…"


def _outcome(tc: Any) -> str:
    if getattr(tc, "duplicate", False):
        return "not re-run (repeat of an earlier call)"
    err = (getattr(tc, "error", None) or "").strip()
    last = _last_line(getattr(tc, "result", "") or "")
    tail = f'; last output line: "{last}"' if last else ""
    if not err:
        return f"exit 0{tail}"
    m = _EXIT_RE.match(err)
    if m:
        return f"exit {m.group(1)}{tail}"
    if "timed out" in err.lower():
        return "timed out"
    first = err.splitlines()[0]
    first = first if len(first) <= _LINE_CHARS else first[:_LINE_CHARS] + "…"
    if tc.name == "bash":
        return f"refused, not run: {first}"
    return f"tool error: {first}"


def commands_after_last_write(tool_calls: Iterable[Any]) -> list[tuple[str, str]]:
    """(command, outcome) for each verification call after the last
    successful write_file/edit_file. No successful write → []."""
    calls = list(tool_calls or [])
    last = None
    for i, tc in enumerate(calls):
        if tc.name in WRITE_TOOLS and not getattr(tc, "error", None):
            last = i
    if last is None:
        return []
    return [(_label(tc), _outcome(tc)) for tc in calls[last + 1:]
            if tc.name in VERIFY_TOOLS]


def build_report(reason: tuple[str, str],
                 files: list[tuple[str, int, int]] | None,
                 commands: list[tuple[str, str]],
                 diff_error: str = "") -> str:
    """The fallback report. `files=None` means the diff could not be computed."""
    cat, raw = reason
    why = f"{cat}: {raw}" if raw and raw.lower() != cat else cat
    if len(why) > 200:
        why = why[:200] + "…"
    lines = [REPORT_HEADER.format(reason=why), "", "## Files changed vs base"]
    if files is None:
        lines.append(f"- unavailable: git diff failed ({diff_error[:200]})")
    elif not files:
        lines.append("- none: the run made no change to the repository")
    else:
        for path, a, d in files[:MAX_FILES]:
            lines.append(f"- `{path}` (+{a}/-{d})")
        if len(files) > MAX_FILES:
            lines.append(f"- … {len(files) - MAX_FILES} more not shown")
    lines += ["", "## Commands run after the last file write"]
    if not commands:
        lines.append("- none recorded")
    else:
        for cmd, outcome in commands[:MAX_COMMANDS]:
            lines.append(f"- `{cmd}`: {outcome}")
        if len(commands) > MAX_COMMANDS:
            lines.append(f"- … {len(commands) - MAX_COMMANDS} more not shown")
    return "\n".join(lines) + "\n"
